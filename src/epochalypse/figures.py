def plot_simulated_planet_mass_period():
    """Companion mass against period for each population, coloured by the
    stellar reflex semimajor axis alpha."""
    from matplotlib.colors import LogNorm, LinearSegmentedColormap
    from matplotlib.lines import Line2D

    # panel order: one/two random on the top row, one/two high-SNR below
    cmap = plt.get_cmap("rainbow")
    cmap = LinearSegmentedColormap.from_list("rainbow_trunc", cmap(np.linspace(0, 1, 256)))

    frames, signatures = [], []
    for name, high_snr, label in C.PANELS:
        frame = read_population(name, high_snr)
        # alpha is recorded per companion at generation time, so it is read
        # rather than recomputed here
        if C.POPULATIONS[name] == 1:
            signatures.append(frame["alpha_mas"].to_numpy())
        else:
            for index in [1, 2]:
                signatures.append(frame[f"alpha_{index}_mas"].to_numpy())
        frames.append((name, label, frame))

    signatures = np.concatenate(signatures)
    signatures = signatures[np.isfinite(signatures) & (signatures > 0)]
    norm = LogNorm(vmin=np.quantile(signatures, 0.01), vmax=np.quantile(signatures, 0.99))

    fig, axes = plt.subplots(2, 2, figsize=(14, 10), sharex=True, sharey=True)
    # constrained_layout would silently override the explicit adjust below
    if hasattr(fig, "set_layout_engine"):
        fig.set_layout_engine("none")

    scatter = None
    for ax, (name, label, frame) in zip(axes.flat, frames):
        if C.POPULATIONS[name] == 1:
            scatter = ax.scatter(frame["period"], frame["mass_pl"],
                                 c=frame["alpha_mas"], norm=norm, cmap=cmap,
                                 s=27, alpha=0.65, linewidths=0, rasterized=True)
        else:
            scatter = ax.scatter(frame["period_1"], frame["mass_pl_1"],
                                 c=frame["alpha_1_mas"], norm=norm, cmap=cmap,
                                 marker="o", s=27, alpha=0.7, linewidths=0,
                                 rasterized=True)
            ax.scatter(frame["period_2"], frame["mass_pl_2"],
                       c=frame["alpha_2_mas"], norm=norm, cmap=cmap,
                       marker="^", s=36, alpha=0.7, linewidths=0, rasterized=True)

        ax.axvline(C.BASELINE_YEARS, color="k", ls="--", lw=2)
        ax.set_xscale("log")
        ax.set_yscale("log")
        # "one companion, random" -> "one companion: random"
        ax.set_title(label.replace(", ", ": "), pad=12, fontsize=27)
        ax.grid(True, which="both", alpha=0.15)
        ax.tick_params(which="both", labelsize=16)

    for ax in axes[-1, :]:
        ax.set_xlabel("orbital period [yr]", fontsize=23)
    for ax in axes[:, 0]:
        ax.set_ylabel(r"companion mass [$M_{\rm Jup}$]", fontsize=23)

    fig.subplots_adjust(left=0.075, right=0.88, top=0.85, bottom=0.085,
                        hspace=0.17, wspace=0.06)
    cax = fig.add_axes([0.905, 0.085, 0.02, 0.775])
    colorbar = fig.colorbar(scatter, cax=cax, orientation="vertical", extend="both")
    colorbar.set_label(r"stellar reflex semimajor axis $\alpha$ [mas]", fontsize=24)
    colorbar.ax.tick_params(labelsize=16)

    # centre the title/legend over the panel block, not the whole figure
    centre_x = 0.5 * (0.075 + 0.88)
    fig.suptitle(r"$\mathtt{epochalypse}$ injected companions", fontsize=36,
                 x=centre_x, y=0.965)
    handles = [
        Line2D([0], [0], marker="o", color="0.35", lw=0, markersize=10,
               label="inner companion"),
        Line2D([0], [0], marker="^", color="0.35", lw=0, markersize=11,
               label="outer companion"),
        Line2D([0], [0], color="k", ls="--", lw=2, label=r"\textit{Gaia} DR4 baseline"),
    ]
    fig.legend(handles=handles, loc="center", bbox_to_anchor=(centre_x, 0.905),
               ncol=3, frameon=False, fontsize=20, columnspacing=2.4, handlelength=1.8)
    return _save(fig, "simulated_planets_mass_period")


