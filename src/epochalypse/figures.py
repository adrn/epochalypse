def add_curved_colorbar(ax, vmin, vmax, cmap, *, side="top", half_angle=20.0,
                        r_in=1.03, r_out=1.07, nseg=256, ticks=None, label="",
                        fontsize=10, text_color="k", edge_color="k"):
    """Colorbar drawn as an annular arc hugging the top or bottom of a healpy
    Mollweide ellipse.

    healpy draws the ellipse as (2 cos t, sin t) in axes data coordinates; the
    band lives between scaled ellipses r_in and r_out over
    t = centre +/- half_angle, with values running vmin (left) -> vmax (right).
    Call after `hp.mollview`, on the healpy axes.
    """
    from matplotlib.collections import PolyCollection

    cmap = plt.get_cmap(cmap) if isinstance(cmap, str) else cmap
    top = side == "top"
    centre = 90.0 if top else -90.0

    t0 = np.radians(centre + (half_angle if top else -half_angle))   # vmin end
    t1 = np.radians(centre - (half_angle if top else -half_angle))   # vmax end
    t = np.linspace(t0, t1, nseg + 1)

    xi, yi = 2.0 * r_in * np.cos(t), r_in * np.sin(t)
    xo, yo = 2.0 * r_out * np.cos(t), r_out * np.sin(t)

    verts = [[(xi[i], yi[i]), (xi[i + 1], yi[i + 1]),
              (xo[i + 1], yo[i + 1]), (xo[i], yo[i])] for i in range(nseg)]
    colors = cmap((np.arange(nseg) + 0.5) / nseg)
    # edgecolor == facecolor kills white hairline seams in PDF output
    ax.add_collection(PolyCollection(verts, facecolors=colors, edgecolors=colors,
                                     linewidths=1, zorder=5))
    ax.plot(np.r_[xi, xo[::-1], xi[:1]], np.r_[yi, yo[::-1], yi[:1]],
            color=edge_color, lw=1, zorder=6)

    if ticks is None:
        ticks = np.linspace(vmin, vmax, 5)
    va = "bottom" if top else "top"
    for value in ticks:
        fraction = (value - vmin) / (vmax - vmin)
        tt = t0 + fraction * (t1 - t0)
        ct, st = np.cos(tt), np.sin(tt)
        ax.plot([2 * r_out * ct, 2 * (r_out + 0.015) * ct],
                [r_out * st, (r_out + 0.015) * st],
                color=edge_color, lw=1, zorder=6)
        angle = np.degrees(np.arctan2(-ct, 2 * st))   # local tangent, reads L->R
        angle = angle - 180 if angle > 90 else (angle + 180 if angle < -90 else angle)
        ax.text(2 * (r_out + 0.03) * ct, (r_out + 0.03) * st, f"{value:g}",
                rotation=angle, rotation_mode="anchor", ha="center", va=va,
                fontsize=fontsize, color=text_color, zorder=6)

    if label:
        ylab = (r_out + 0.135) if top else -(r_out + 0.135)
        ax.text(0.0, ylab, label, ha="center", va=va, fontsize=fontsize + 1,
                color=text_color, zorder=6)

    y0, y1 = ax.get_ylim()
    if top:
        ax.set_ylim(min(y0, -1.05), max(y1, r_out + 0.24))
    else:
        ax.set_ylim(min(y0, -(r_out + 0.24)), max(y1, 1.05))
    x0, x1 = ax.get_xlim()
    ax.set_xlim(min(x0, -2.05), max(x1, 2.05))


def _decorate_skymap(ax, display_grat, foreign_grat, label_coord, *, fontsize=9):
    """Graticules, meridian/parallel labels, and the FoV-transit colorbar."""
    import healpy as hp

    hp.visufunc.graticule(coord=foreign_grat, c="silver", linestyle="solid",
                          lw=0.3, dpar=30, dmer=30, alpha=0.5)
    hp.visufunc.graticule(coord=display_grat, c="w", linestyle="dashed",
                          lw=0.4, dpar=30, dmer=30)
    for lat in [-90, -60, -30, 30, 60]:
        hp.visufunc.projtext(0, lat, rf"{lat}$^\circ$", lonlat=True,
                             coord=label_coord, fontweight="bold",
                             fontsize=fontsize, color="silver",
                             ha="left", va="bottom")
    for lon in [-150, -120, -90, -60, -30, 0, 30, 60, 90, 120, 150]:
        hp.visufunc.projtext(lon % 360, 0, rf"{lon}$^\circ$", lonlat=True,
                             coord=label_coord, fontweight="bold",
                             fontsize=fontsize, color="silver",
                             ha="left", va="bottom")
    ax.text(-2.0, 0.0, r"180$^\circ$", fontweight="bold", ha="left",
            va="bottom", fontsize=fontsize, color="silver")
    ax.text(2.005, 0.0, r"-180$^\circ$", fontweight="bold", ha="left",
            va="bottom", fontsize=fontsize, color="silver")

    image = ax.get_images()[0]
    vmin, vmax = image.get_clim()
    add_curved_colorbar(ax, vmin, vmax, "bone", side="top", ticks=[0, 100, 200],
                        label="number of FoV transits", fontsize=18)


def plot_star_sky_scanlaw():
    """Parent sample on the sky over the GOST DR4 FoV-transit map.

    One panel per display frame: colour is distance, marker area scales with
    stellar mass, and the two curved colorbars hug the ellipse (transits on
    top, distance on the bottom). The map is stored in equatorial coordinates;
    only the display frame changes between panels.
    """
    import healpy as hp
    from matplotlib.colors import Normalize, LinearSegmentedColormap
    from matplotlib.lines import Line2D

    gost_path = C.GOST_FOV_MAP
    if not gost_path.exists():
        print(f"  skipping star_sky_scanlaw: {gost_path} not found")
        return []

    # five columns of a 117-column, multi-GB CSV at 4M stars
    stars = pd.read_csv(C.stars_csv(), low_memory=False,
                        usecols=["ra", "dec", "parallax", "mass_interp", "sig_AL"])
    # the final parent sample: finite astrometry, positive parallax/mass, and a
    # usable noise model
    sky = stars.loc[
        np.isfinite(stars["ra"]) & np.isfinite(stars["dec"])
        & np.isfinite(stars["parallax"]) & (stars["parallax"] > 0)
        & np.isfinite(stars["mass_interp"]) & (stars["mass_interp"] > 0)
        & stars["sig_AL"].notna()
    ].copy()
    sky["distance_pc"] = 1000.0 / sky["parallax"]
    print(f"  {len(sky):,} stars in the parent sample")

    transit_map = hp.read_map(str(gost_path))

    def marker_area(mass):
        return C.MASS_MARKER_FLOOR + C.MASS_MARKER_SCALE * np.asarray(mass)

    plasma = plt.get_cmap("plasma")
    # clip plasma's darkest end so nearby stars stay visible on dark map pixels
    star_cmap = LinearSegmentedColormap.from_list(
        "plasma_clipped", plasma(np.linspace(C.STAR_CMAP_CLIP, 1.0, 256)))
    star_norm = Normalize(vmin=0.0, vmax=C.DISTANCE_VMAX_PC)

    written = []
    for frame in C.SKY_FRAMES:
        if frame == "equatorial":
            mollview_coord, display_grat, foreign_grat, label_coord = \
                "C", "Equatorial", "Ecliptic", "C"
        else:
            mollview_coord, display_grat, foreign_grat, label_coord = \
                ["C", "E"], "Ecliptic", "Equatorial", "E"

        fig = plt.figure(figsize=C.SKYMAP_FIGSIZE)
        hp.visufunc.mollview(transit_map, fig=fig.number, coord=mollview_coord,
                             title="", cbar=False, cmap="bone", notext=True,
                             min=C.TRANSIT_VMIN, max=C.TRANSIT_VMAX,
                             badcolor="white", bgcolor="white", flip="astro")
        ax = plt.gca()

        # rasterized: at 4M stars a vector scatter is a PDF no viewer opens
        hp.visufunc.projscatter(sky["ra"].to_numpy(), sky["dec"].to_numpy(),
                                lonlat=True, coord="C",
                                c=sky["distance_pc"].to_numpy(),
                                s=marker_area(sky["mass_interp"].to_numpy()),
                                cmap=star_cmap, norm=star_norm,
                                edgecolors="k", linewidths=0.12, alpha=0.88,
                                zorder=10, rasterized=True)

        _decorate_skymap(ax, display_grat, foreign_grat, label_coord)
        add_curved_colorbar(ax, 0, C.DISTANCE_VMAX_PC, star_cmap,
                            side="bottom", ticks=[0, 50, 100, 150, 200, 250],
                            label="distance [pc]", fontsize=18)

        handles = [
            Line2D([], [], marker="o", linestyle="none", markerfacecolor="0.3",
                   markeredgecolor="k", markeredgewidth=0.2,
                   markersize=np.sqrt(marker_area(mass)),
                   label=rf"{mass:g} $M_\odot$")
            for mass in C.MASS_LEGEND_MSUN
        ]
        ax.legend(handles=handles, title="stellar mass", loc="center left",
                  bbox_to_anchor=(1.01, 0.5), frameon=True, fontsize=13,
                  title_fontsize=18)

        written += _save(fig, f"star_sky_scanlaw_{frame}")
    return written


