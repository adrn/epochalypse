def make_figures(names=None):
    """Build the requested catalog-generation figures.

    A figure whose inputs are missing is reported and skipped, so one absent
    population does not abort the rest of the set.
    """
    _apply_style()
    selected = list(names) if names else list(C.FIGURES)
    unknown = [name for name in selected if name not in BUILDERS]
    if unknown:
        raise KeyError(f"unknown figure(s): {unknown}; available: {sorted(BUILDERS)}")

    written = []
    for name in selected:
        print(f"\n[{name}]")
        try:
            written += BUILDERS[name]() or []
        except FileNotFoundError as error:
            print(f"  skipped: {error}")
    return written
