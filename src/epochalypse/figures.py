def orbit_points_au(a, e, inc, node, argument, n=500):
    """On-sky Keplerian ellipse in AU, following Hilditch (2004)."""
    argument, node, inc = np.radians(argument), np.radians(node), np.radians(inc)
    A = a * (np.cos(argument) * np.cos(node)
             - np.sin(argument) * np.sin(node) * np.cos(inc))
    B = a * (np.cos(argument) * np.sin(node)
             + np.sin(argument) * np.cos(node) * np.cos(inc))
    F = a * (-np.sin(argument) * np.cos(node)
             - np.cos(argument) * np.sin(node) * np.cos(inc))
    G = a * (-np.sin(argument) * np.sin(node)
             + np.cos(argument) * np.cos(node) * np.cos(inc))
    eccentric_anomaly = np.linspace(0, 2 * np.pi, n)
    X = np.cos(eccentric_anomaly) - e
    Y = np.sqrt(1 - e**2) * np.sin(eccentric_anomaly)
    return B * X + G * Y, A * X + F * Y


def plot_companion_gallery():
    """One row per companion population, each showing sample on-sky orbits."""
    from matplotlib.lines import Line2D

    inner_color, outer_color = C.INNER_COLOR, C.OUTER_COLOR
    n_per_row = C.GALLERY_N_PER_ROW

    panels = [(name, high_snr, "\n".join(label.split(", ")))
              for name, high_snr, label in C.PANELS]

    def compact(value):
        """No scientific notation, ~2 significant figures."""
        value = float(value)
        if value >= 10:
            return f"{value:.0f}"
        return f"{value:.1f}" if value >= 1 else f"{value:.2g}"

    fig, axes = plt.subplots(len(panels), n_per_row,
                             figsize=(n_per_row * 2.05, len(panels) * 2.55),
                             squeeze=False)

    for row, (name, high_snr, label) in enumerate(panels):
        frame = read_population(name, high_snr)
        sample = frame.sample(min(n_per_row, len(frame)),
                              random_state=C.GALLERY_SEED).reset_index(drop=True)

        for column in range(n_per_row):
            ax = axes[row, column]
            ax.set_xticks([])
            ax.set_yticks([])
            for spine in ax.spines.values():
                spine.set_color("0.7")
            if column >= len(sample):
                ax.axis("off")
                continue

            system = sample.iloc[column]
            if C.POPULATIONS[name] == 1:
                x, y = orbit_points_au(system["sma"], system["ecc"], system["inc"],
                                       system["Omega"], system["omega"])
                ax.plot(x, y, lw=3, color=inner_color)
                title = (rf"$M={compact(system['mass_pl'])}$" "\n"
                         rf"$P={compact(system['period'])}$" "\n"
                         rf"$e={system['ecc']:.2f}$" "\n"
                         rf"$i={system['inc']:.0f}$")
            else:
                for suffix, color in [("_1", inner_color), ("_2", outer_color)]:
                    x, y = orbit_points_au(
                        system[f"sma{suffix}"], system[f"ecc{suffix}"],
                        system[f"inc{suffix}"], system[f"Omega{suffix}"],
                        system[f"omega{suffix}"])
                    ax.plot(x, y, lw=3, color=color)
                title = (rf"$M=[{compact(system['mass_pl_1'])},"
                         rf"{compact(system['mass_pl_2'])}]$" "\n"
                         rf"$P=[{compact(system['period_1'])},"
                         rf"{compact(system['period_2'])}]$" "\n"
                         rf"$e=[{system['ecc_1']:.2f},{system['ecc_2']:.2f}]$" "\n"
                         rf"$i=[{system['inc_1']:.0f},{system['inc_2']:.0f}]$")

            ax.plot(0, 0, marker="*", color="k", ms=9, markeredgecolor="k",
                    markeredgewidth=0.6, zorder=5)
            ax.set_aspect("equal", adjustable="datalim")
            ax.set_title(title, fontsize=16, linespacing=1.2)

        axes[row, 0].set_ylabel(label, fontsize=19, labelpad=10, linespacing=1.15)

    handles = [
        Line2D([0], [0], color=inner_color, lw=2.5, label="inner companion"),
        Line2D([0], [0], color=outer_color, lw=2.5, label="outer companion"),
        Line2D([0], [0], marker="*", color="k", lw=0, markersize=14,
               markeredgecolor="k", markeredgewidth=0.5, label="host star"),
    ]
    fig.legend(handles=handles, loc="upper center", ncol=3, frameon=False,
               fontsize=24, bbox_to_anchor=(0.5, 0.955), columnspacing=2.4)
    fig.suptitle(rf"{len(panels) * n_per_row} $\mathtt{{epochalypse}}$ injected "
                 r"companion systems (on-sky orbits)", fontsize=45, y=0.992)
    fig.text(0.5, 0.016,
             r"per panel:\ \ $M$ [$M_{\rm J}$]\quad $P$ [yr]\quad $e$\quad "
             r"$i$ [deg];\ \ listed as [inner, outer]",
             ha="center", va="bottom", fontsize=22, color="0.30")
    fig.tight_layout(rect=[0, 0.045, 1, 0.925])
    return _save(fig, "companion_gallery")


