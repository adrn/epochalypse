"""Catalog-generation figures.

The five paper figures that describe the catalog itself, ported from
`load_stars.ipynb`, `sim_planets.ipynb`, and `analysis/schematic_figure.ipynb`:

    star_sky_scanlaw_<frame>     parent sample over the DR4 scan law
    population_schematic         selection funnel + population branching
    pop_diagnostics_1planet      one-companion prior distributions
    pop_diagnostics_2planet      two-companion prior distributions
    companion_gallery            sample on-sky orbits, one row per population
    simulated_planets_mass_period  mass vs. period, coloured by signature alpha

The later analysis figures (characterizability maps, the LW25 comparison) stay
in `analysis/`, since they need the periodogram characterization rather than the
catalog alone.

Colours, sizes, and formats are module constants in `config.py`; annotations
that quote numbers (sample counts, prior ranges) are read from the config and
the catalog on disk, so they cannot drift away from what was actually run.

The figures are unchanged from the serial pipeline, including the random vs
high-SNR comparisons. What changed is where the high-SNR sample comes from: it
is no longer generated by rejection sampling but selected after the fact as the
top `HIGH_SNR_FRACTION` of a random population by recorded SNR_tot. Every
figure reads through `read_population(name, high_snr=...)`, which applies that
cut and maps the sharded truth schema onto the column names the figures use.
"""
from __future__ import annotations

from functools import lru_cache

import numpy as np
import pandas as pd
import matplotlib
import matplotlib.pyplot as plt

from . import config as C
from .sources import select_high_snr


def _apply_style():
    """Global typography for every figure in this module."""
    matplotlib.rc("xtick", labelsize=18)
    matplotlib.rc("ytick", labelsize=18)
    matplotlib.rc("font", **{"family": C.FONT_FAMILY,
                             "serif": [C.SERIF_FONT]})
    matplotlib.rc("text", usetex=C.USETEX)


def _save(fig, stem):
    """Write one figure in every configured format; returns the paths."""
    C.figure_dir().mkdir(parents=True, exist_ok=True)
    written = []
    for suffix in C.FORMATS:
        path = C.figure_dir() / f"{stem}.{suffix}"
        if suffix == "png":
            fig.savefig(path, bbox_inches="tight", dpi=C.PNG_DPI)
        else:
            fig.savefig(path, bbox_inches="tight")
        written.append(path)
    print(f"  wrote {', '.join(str(p) for p in written)}")
    plt.close(fig)
    return written


def read_population(population, high_snr=False):
    """See `_read_population`; this only normalizes the cache key.

    `lru_cache` keys on the argument tuple, so `read_population(p)` and
    `read_population(p, False)` would otherwise be two entries -- and the
    figures call it both ways.
    """
    return _read_population(population, bool(high_snr))


@lru_cache(maxsize=None)
def _read_population(population, high_snr):
    """A population as a DataFrame, in the column names the figures expect.

    Reads the merged truth table (or the shard files) and renames the sharded
    schema back to the legacy figure columns: `sma_1 -> sma` for one-companion
    populations, `alpha_mas_k -> alpha_k_mas`, `mass_st_msun -> mass_st`,
    `parallax_mas -> parallax`.

    Cached: a full figure set asks for the same four tables sixteen times, and
    at 4M systems each one is a GB-scale parquet decode. The figures only ever
    read the frames, never mutate them, so one copy is shared.

    For a high-SNR view this prefers the table the `select` stage already wrote
    -- 1% of the rows -- and only falls back to recomputing the cut if that file
    is absent.
    """
    if high_snr:
        selected = C.truths(population, high_snr=True)
        if selected.exists():
            frame = pd.read_parquet(selected)
        else:
            frame = select_high_snr(_read_population(population, False))
    else:
        merged = C.truths(population)
        if merged.exists():
            frame = pd.read_parquet(merged)
        else:
            parts = sorted(C.shard_dir(population).glob("truths_*.parquet"))
            if not parts:
                raise FileNotFoundError(
                    f"no truth table for {population}: neither {merged} nor shards "
                    f"in {C.shard_dir(population)}")
            frame = pd.concat([pd.read_parquet(p) for p in parts], ignore_index=True)

    frame = frame.rename(columns={"mass_st_msun": "mass_st", "parallax_mas": "parallax",
                                  "mass_interp": "mass_st"})
    for k in (1, 2):
        if f"alpha_mas_{k}" in frame.columns:
            frame = frame.rename(columns={f"alpha_mas_{k}": f"alpha_{k}_mas"})
    if C.POPULATIONS[population] == 1:
        frame = frame.rename(columns={c: c[:-2] for c in frame.columns
                                      if c.endswith("_1") and c != "alpha_1_mas"})
        frame = frame.rename(columns={"alpha_1_mas": "alpha_mas"})
    return frame


