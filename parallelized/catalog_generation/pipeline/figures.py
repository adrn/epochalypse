def plot_population_schematic(config: CatalogConfig):
    """Selection funnel (G23H -> parent) and the population branching.

    Every number and the prior annotation are read from the configuration and
    the catalogs on disk, so the schematic always describes the run that
    produced them.
    """
    import pyarrow as pa
    import pyarrow.ipc as ipc
    from matplotlib.patches import FancyBboxPatch, FancyArrowPatch, Rectangle

    settings = config.figures
    priors = config.priors
    ink = settings.ink_color
    points = 1 / 66.0   # ~data units per point at this figure scale

    def box(ax, cx, cy, w, h, facecolor, title, lines=None, textcolor=ink,
            fontsize=10.0, title_fs=12.0, edgecolor="none", lw=1.4):
        """Rounded box whose title+body block is truly vertically centred."""
        x, y = cx - w / 2, cy - h / 2
        ax.add_patch(FancyBboxPatch(
            (x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.10",
            linewidth=lw, facecolor=facecolor, edgecolor=edgecolor, zorder=3))
        if lines:
            gap, title_h = 0.16, title_fs * points
            top0 = cy + h / 2.0
            t_title = ax.text(cx, top0, title, ha="center", va="top",
                              fontsize=title_fs, fontweight="bold",
                              color=textcolor, zorder=4)
            t_body = ax.text(cx, top0 - title_h - gap, "\n".join(lines),
                             ha="center", va="top", fontsize=fontsize,
                             color=textcolor, zorder=4, linespacing=1.45)
            # measure the rendered extent and shift so the block centres on cy
            fig = ax.figure
            fig.canvas.draw()
            renderer = fig.canvas.get_renderer()
            inverse = ax.transData.inverted()

            def yspan(text):
                bb = text.get_window_extent(renderer)
                (_, ylo), (_, yhi) = inverse.transform([(bb.x0, bb.y0), (bb.x0, bb.y1)])
                return ylo, yhi

            tlo, thi = yspan(t_title)
            blo, bhi = yspan(t_body)
            dy = cy - 0.5 * (max(thi, bhi) + min(tlo, blo))
            t_title.set_y(top0 + dy)
            t_body.set_y(top0 - title_h - gap + dy)
        else:
            ax.text(cx, cy, title, ha="center", va="center", fontsize=title_fs,
                    fontweight="bold", color=textcolor, zorder=4)
        return {"L": (x, cy), "R": (x + w, cy), "T": (cx, y + h), "B": (cx, y)}

    def arrow(ax, p0, p1, color=ink, lw=1.9, rad=0.0):
        ax.add_patch(FancyArrowPatch(
            p0, p1, arrowstyle="-|>", mutation_scale=15, lw=lw, color=color,
            connectionstyle=f"arc3,rad={rad}", zorder=1, shrinkA=2, shrinkB=3))

    # ---- counts, straight from the inputs and the generated catalogs ----
    with pa.memory_map(str(config.paths.g23h_sample), "r") as handle:
        n_g23h = ipc.open_file(handle).read_all().num_rows
    stars = pd.read_csv(config.paths.stars_csv, usecols=["sig_AL"])
    n_after_pecaut = len(stars)
    n_parent = int(np.isfinite(stars["sig_AL"]).sum())
    drop_pecaut = n_g23h - n_after_pecaut
    drop_sigal = n_after_pecaut - n_parent

    def count(spec):
        return len(read_population(config, spec))

    def resonant(spec):
        column = read_population(config, spec)["near_resonance"]
        n = int(column.sum())
        return n, 100.0 * n / len(column)

    spec_a1 = _population_by(config, 1, False)
    spec_d1 = _population_by(config, 1, True)
    spec_a2 = _population_by(config, 2, False)
    spec_d2 = _population_by(config, 2, True)
    n_a1, n_d1, n_a2, n_d2 = (count(s) for s in (spec_a1, spec_d1, spec_a2, spec_d2))
    drop_d1, drop_d2 = n_a1 - n_d1, n_a2 - n_d2
    n_res_a2, frac_res_a2 = resonant(spec_a2)
    n_res_d2, frac_res_d2 = resonant(spec_d2)

    print(f"  funnel: G23H {n_g23h:,} -> Pecaut {n_after_pecaut:,} (-{drop_pecaut}) "
          f"-> parent {n_parent:,} (-{drop_sigal})")
    print(f"  pops  : control {n_parent:,} | 1c {n_a1:,}/{n_d1:,} (-{drop_d1}) "
          f"| 2c {n_a2:,}/{n_d2:,} (-{drop_d2})")


    fig, ax = plt.subplots(figsize=(14.0, 14.0 / 1.759))
    ax.set_xlim(0.1, 15.4)
    ax.set_ylim(0.3, 9.0)
    ax.set_aspect("equal")
    ax.axis("off")

    # bands group by companion count, not by selection regime
    band = "#ECEFF3"
    ax.add_patch(Rectangle((0.75, 0.95), 3.00, 3.35, facecolor=band, zorder=0))
    ax.add_patch(Rectangle((3.85, 0.95), 5.75, 3.35, facecolor=band, zorder=0))
    ax.add_patch(Rectangle((9.70, 0.95), 5.75, 3.35, facecolor=band, zorder=0))
    for x, text in [(2.25, "zero companions"), (6.72, "one companion"),
                    (12.57, "two companions")]:
        ax.text(x, 4.02, text, ha="center", va="center", fontsize=24,
                fontweight="bold", color=ink)

    # ---- top: the horizontal selection funnel ----
    col_funnel, col_parent = settings.funnel_color, settings.parent_color
    g = box(ax, 2.60, 7.85, 2.95, 1.45, col_funnel, r"\texttt{G23H} catalog",
            [r"DR2-DR3 cross-match", r"$G<16$"], title_fs=23, fontsize=15)
    b1 = box(ax, 5.90, 7.85, 3.05, 1.55, col_funnel, f"{n_g23h:,} stars",
             [r"$\varpi\geq4$ mas ($d\leq250$ pc);", "uniform-in-distance draw"],
             title_fs=23, fontsize=15)
    b2 = box(ax, 9.20, 7.85, 2.95, 1.35, col_funnel, f"{n_after_pecaut:,} stars",
             [rf"$-{drop_pecaut}$: brighter than P\&M13"], title_fs=23, fontsize=15)
    parent = box(ax, 12.50, 7.85, 3.05, 1.55, col_parent, "parent sample",
                 [rf"$-{drop_sigal}$: no $\sigma_{{\rm AL}}$ (DR3)",
                  f"n = {n_parent:,}"], title_fs=27, fontsize=16)

    for start, end in [(g["R"], b1["L"]), (b1["R"], b2["L"]), (b2["R"], parent["L"])]:
        arrow(ax, start, end, color=col_funnel, lw=2.8)

    # prior annotation, written out of the configured priors
    mass_min_mars = priors.mass_min_mjup / settings.mars_mass_mjup
    ax.text(12.5, 6.3,
            "per-companion priors:\n"
            rf"$M_p\in[{mass_min_mars:.3g}\,M_{{\rm Mars}},\,"
            rf"{priors.mass_max_mjup:g}\,M_{{\rm Jup}}]$ log-uniform" "\n"
            rf"$a\in[{priors.a_min_au:g},{priors.a_max_au:g}]$ au log-uniform" "\n"
            rf"$e\sim\mathcal{{U}}({priors.ecc_min:g},{priors.ecc_max:g})$; "
            r"isotropic angles",
            ha="center", va="center", fontsize=15, color=ink, linespacing=1.5,
            bbox=dict(boxstyle="round,pad=0.5", fc="white", ec=col_parent, lw=1.2))

    # ---- bottom: control + the one/two-companion groups ----
    width, height, y_box = 2.80, 2.55, 2.35
    # the high-SNR populations are selected after generation, not drawn
    snr_line = rf"top {100 * settings.high_snr_fraction:g}\% by $\mathrm{{SNR_{{tot}}}}$"
    ctrl = box(ax, 2.25, y_box, width, height, settings.control_color, "control",
               [f"n = {n_parent:,}"], title_fs=27, fontsize=16)
    a1 = box(ax, 5.30, y_box, width, height, settings.schematic_random_color,
             "random", [f"n = {n_a1:,}"], title_fs=27, fontsize=16)
    d1 = box(ax, 8.10, y_box, width, height, settings.schematic_high_snr_color,
             "high-SNR", [snr_line, rf"selected, not drawn", f"n = {n_d1:,}"],
             title_fs=27, fontsize=16)
    a2 = box(ax, 11.15, y_box, width, height, settings.schematic_random_color,
             "random", [r"hill-stable",
                        rf"{n_res_a2} resonant ({frac_res_a2:.1f}\%)",
                        f"n = {n_a2:,}"], title_fs=27, fontsize=16)
    d2_lines = [r"hill-stable", rf"{n_res_d2} resonant ({frac_res_d2:.1f}\%)",
                snr_line, r"selected, not drawn", f"n = {n_d2:,}"]
    d2 = box(ax, 13.95, y_box, width, height, settings.schematic_high_snr_color,
             "high-SNR", d2_lines, title_fs=27, fontsize=16)

    # parent fans out to each population, stopping at the band headers
    header_y = 4.30
    for target, color, rad in [(ctrl, "#5A6B7B", 0.20),
                               (a1, settings.random_color, 0.13),
                               (d1, settings.high_snr_color, 0.07),
                               (a2, settings.random_color, -0.01),
                               (d2, settings.high_snr_color, -0.10)]:
        arrow(ax, parent["B"], (target["T"][0], header_y), color=color, lw=2.8, rad=rad)

    coplanar_pct = 100 * priors.coplanar_probability
    ax.text(12.57, 0.60,
            rf"{coplanar_pct:.0f}/{100 - coplanar_pct:.0f} coplanar vs. "
            r"mutually inclined; $a_1<a_2$",
            ha="center", va="center", fontsize=15, color=ink, style="italic")
    ax.set_title(r"the \texttt{epochalypse} injected populations",
                 fontsize=45, fontweight="bold", pad=4)
    fig.tight_layout()
    return _save(fig, config, "population_schematic")


