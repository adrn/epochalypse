"""Catalog-generation figures.

The five paper figures that describe the catalog itself, ported from
`load_stars.ipynb`, `sim_planets.ipynb`, and `analysis/schematic_figure.ipynb`:

    star_sky_scanlaw_<frame>     parent sample over the DR4 scan law
    population_schematic         selection funnel + population branching
    pop_diagnostics_1planet      one-companion prior distributions
    pop_diagnostics_2planet      two-companion prior distributions
    companion_gallery            sample on-sky orbits, one row per population
    simulated_planets_mass_period  mass vs. period, coloured by signature alpha

The later analysis figures (characterizability maps, the LW25 comparison) stay
in `analysis/`, since they need the periodogram characterization rather than the
catalog alone.

Colours, sizes, and formats come from `config.figures`; annotations that quote
numbers (sample counts, prior ranges) are generated from the configuration and
the catalog on disk, so they cannot drift away from what was actually run.

The figures are unchanged from the serial pipeline, including the random vs
high-SNR comparisons. What changed is where the high-SNR population comes from:
it is no longer generated by rejection sampling but selected after the fact as
the top `high_snr_fraction` of the random population by recorded SNR_tot. Every
figure reads through `read_population`, which applies that cut for a derived
population and maps the sharded truth schema onto the column names the figures
already used.
"""
from __future__ import annotations

import numpy as np
import pandas as pd
import matplotlib
import matplotlib.pyplot as plt

from .config import CatalogConfig


def _apply_style(settings):
    """Global typography for every figure in this module."""
    matplotlib.rc("xtick", labelsize=18)
    matplotlib.rc("ytick", labelsize=18)
    matplotlib.rc("font", **{"family": settings.font_family,
                             "serif": [settings.serif_font]})
    matplotlib.rc("text", usetex=settings.usetex)


def _save(fig, config, stem):
    """Write one figure in every configured format; returns the paths."""
    settings = config.figures
    config.paths.figure_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for suffix in settings.formats:
        path = config.paths.figure_dir / f"{stem}.{suffix}"
        if suffix == "png":
            fig.savefig(path, bbox_inches="tight", dpi=settings.png_dpi)
        else:
            fig.savefig(path, bbox_inches="tight")
        written.append(path)
    print(f"  wrote {', '.join(str(p) for p in written)}")
    plt.close(fig)
    return written


def _population_by(config, n_companions, high_snr):
    """The spec for a given companion count and selection state."""
    for spec in config.populations:
        if spec.n_companions == n_companions and bool(spec.derive_from) == bool(high_snr):
            return spec
    return None


def read_population(config, spec):
    """A population as a DataFrame, in the column names the figures expect.

    Reads the merged truth table (or the shard files), applies the top-fraction
    SNR_tot cut when `spec` is a derived high-SNR population, and renames the
    sharded schema back to the legacy figure columns: `sma_1 -> sma` for
    one-companion populations, `alpha_mas_k -> alpha_k_mas`, `mass_st_msun ->
    mass_st`, `parallax_mas -> parallax`.
    """
    generated = config.population(spec.derive_from) if spec.derive_from else spec

    merged = config.paths.data_dir / f"injected_solutions_{generated.name}.parquet"
    if merged.exists():
        frame = pd.read_parquet(merged)
    else:
        parts = sorted(config.paths.shard_dir(generated.name).glob("truths_*.parquet"))
        if not parts:
            raise FileNotFoundError(
                f"no truth table for {generated.name}: neither {merged} nor shards "
                f"in {config.paths.shard_dir(generated.name)}")
        frame = pd.concat([pd.read_parquet(p) for p in parts], ignore_index=True)

    if spec.derive_from:
        frame = select_high_snr(frame, spec.high_snr_fraction)

    frame = frame.rename(columns={"mass_st_msun": "mass_st", "parallax_mas": "parallax",
                                  "mass_interp": "mass_st"})
    for k in (1, 2):
        if f"alpha_mas_{k}" in frame.columns:
            frame = frame.rename(columns={f"alpha_mas_{k}": f"alpha_{k}_mas"})
    if generated.n_companions == 1:
        frame = frame.rename(columns={c: c[:-2] for c in frame.columns
                                      if c.endswith("_1") and c != "alpha_1_mas"})
        frame = frame.rename(columns={"alpha_1_mas": "alpha_mas"})
    return frame


def select_high_snr(frame, fraction):
    """The top `fraction` of systems by detectability.

    A system's detectability is the largest SNR_tot over its companions, matching
    how the old generated high-SNR populations required *every* companion to be
    detectable only in the sense of being drawn from the same threshold -- here
    the ranking is per system and the threshold is a quantile, so the size of the
    selection is fixed and the cut value is whatever the data says it is.
    """
    columns = [c for c in ("snr_total_1", "snr_total_2") if c in frame.columns]
    if not columns:
        raise KeyError("no snr_total_* columns to rank on")
    with np.errstate(invalid="ignore"):
        score = np.nanmax(frame[columns].to_numpy(float), axis=1)
    frame = frame.assign(_snr_rank=score)
    n_keep = max(1, int(round(fraction * len(frame))))
    selected = frame.nlargest(n_keep, "_snr_rank").drop(columns="_snr_rank")
    return selected.sort_values("gaia_source_id").reset_index(drop=True)


